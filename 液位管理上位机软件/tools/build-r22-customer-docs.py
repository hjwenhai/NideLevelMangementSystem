def make(name,pages):
    doc=Document();section=doc.sections[0]
    section.page_width=Inches(8.5);section.page_height=Inches(11)
    section.top_margin=Inches(.64);section.bottom_margin=Inches(.6)
    section.left_margin=section.right_margin=Inches(.75)
    for s in ['Normal','Title','Subtitle','Heading 1','Heading 2','List Paragraph']:
        st=doc.styles[s];st.font.name='Microsoft YaHei';st.font.color.rgb=RGBColor(0,0,0);st.font.italic=False
        st.element.get_or_add_rPr().rFonts.set(qn('w:eastAsia'),'微软雅黑')
    normal=doc.styles['Normal'];normal.font.size=Pt(10.8);normal.paragraph_format.line_spacing=1.25;normal.paragraph_format.space_after=Pt(7)
    for s,size in [('Title',23),('Heading 1',17),('Heading 2',12)]:
        doc.styles[s].font.size=Pt(size);doc.styles[s].paragraph_format.space_before=Pt(8);doc.styles[s].paragraph_format.space_after=Pt(8)
    footer=section.footer.paragraphs[0];footer.alignment=2
    footer.add_run('r22-u2 中文测试版  ·  ')
    field=OxmlElement('w:fldSimple');field.set(qn('w:instr'),'PAGE');footer._p.append(field)
    for r in footer.runs:r.font.size=Pt(9)
    html=['<!doctype html><meta charset="utf-8"><style>body{font:16px/1.8 Microsoft YaHei,sans-serif;max-width:1000px;margin:36px auto;padding:0 24px;color:#182f3a}h1,h2{color:#000}section{margin-bottom:36px}p{margin:10px 0}h3{margin:18px 0 7px;font-size:19px}a{color:#138579}@media print{section{break-before:page}}</style>']
    for i,(title,blocks) in enumerate(pages):
        if i:doc.add_page_break()
        doc.add_paragraph(title,'Title' if i==0 else 'Heading 1')
        if i==0:doc.add_paragraph('液位管理系统  r22-u2  2026年11月7日','Subtitle')
        html.append('<section><h1>'+escape(title)+'</h1>')
        n=0
        for kind,text in blocks:
            if kind=='h':doc.add_paragraph(text,'Heading 2');html.append('<h3>'+escape(text)+'</h3>');n=0
            else:
                if kind=='step':n+=1;text=f'{n}  '+text
                p=doc.add_paragraph(text)
                p.paragraph_format.widow_control=True
                html.append('<p>'+escape(text)+'</p>')
        html.append('</section>')
    for style in doc.styles:
        if style.type==1:
            pr=style.element.get_or_add_pPr()
            for border in list(pr.findall(qn('w:pBdr'))):pr.remove(border)
    for para in doc.paragraphs:
        if para.style.name=='Title':
            pr=para._p.get_or_add_pPr();border=OxmlElement('w:pBdr')
            for side in ['top','left','bottom','right','between']:
                edge=OxmlElement('w:'+side);edge.set(qn('w:val'),'nil');border.append(edge)
            pr.append(border)
    doc.core_properties.title=pages[0][0];doc.core_properties.author='耐德东京计装';doc.core_properties.comments=''
    output=dest/(name+'.docx');doc.save(output)
    (dest/(name+'.html')).write_text('\n'.join(html),encoding='utf-8')
    return str(output)


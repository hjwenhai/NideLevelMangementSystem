"""Generate the active V3 Go constants; keep V2 reference immutable."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
s=json.loads((root/'protocols/north-v3.json').read_text(encoding='utf-8'))
d=json.loads((root/'docs/附件/north-v3-design.json').read_text(encoding='utf-8'))
assert s['version']==3 and s['capacity']==64
assert [r for r in s['regions'] if r['name']!='simple_control']==d['preserved_data_regions']
assert s['control_fields']==d['control_fields'] and s['commands']==d['commands']
assert next(r for r in s['regions'] if r['name']=='simple_control')==d['control_region']
seen=set()
for r in s['regions']:
 a=set(range(r['base'],r['base']+r['count']*r['stride']))
 assert a and not a.intersection(seen) and max(a)<65536
 seen.update(a)
assert next(r for r in s['regions'] if r['name']=='simple_control')['base']==30000
assert s['gateway_commands']==d['gateway_commands']
camel=lambda n:''.join(x[:1].upper()+x[1:] for x in n.split('_'))
lines=['// Code generated by tools/generate_v3_map.py; DO NOT EDIT.','package protocols','const (','MapVersion=3','Capacity=64','MaxPerSouthPort=16']
for r in s['regions']:
 for k in ['base','stride','count']:lines.append(f"{camel(r['name'])}{camel(k)}={r[k]}")
for f in s['summary_fields']:lines.append(f"Summary{camel(f['name'])}={f['offset']}")
lines+=[')','']
lines += ['// Command semantics confirmed by customer C01 on 2026-10-13.',
          'func SouthAction(command uint16) (uint16, bool) {', 'switch command {']
for c in s['commands']:
 lines.append(f"case {c['value']}: return {c['south_HR699']}, true // {c['chinese']}")
lines += ['default: return 0, false', '}', '}', '']
(root/'protocols/layout_generated.go').write_text('\n'.join(lines),encoding='utf-8')
print('Generated V3, 64 slots, D2 control; V2 read mappings preserved')
